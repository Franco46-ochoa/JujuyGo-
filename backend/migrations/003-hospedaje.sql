CREATE TABLE IF NOT EXISTS hospedaje (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  slug text NOT NULL UNIQUE,
  tipo text NOT NULL CHECK (tipo IN ('hotel', 'hosteria', 'posada', 'refugio', 'camping')),
  localidad text NOT NULL,
  zona_slug text,
  descripcion text,
  contacto_url text,
  fuente text NOT NULL DEFAULT 'por verificar',
  verificado boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS hospedaje_zona_slug_idx ON hospedaje(zona_slug);

CREATE TABLE IF NOT EXISTS guia (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  zona_slug text,
  especialidad text,
  fuente text NOT NULL DEFAULT 'por verificar',
  verificado boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS guia_zona_slug_idx ON guia(zona_slug);

