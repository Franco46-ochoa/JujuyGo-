CREATE TABLE IF NOT EXISTS zona (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  slug text NOT NULL UNIQUE,
  descripcion text NOT NULL,
  orden integer NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS lugar (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zona_id integer NOT NULL REFERENCES zona(id) ON DELETE CASCADE,
  nombre text NOT NULL,
  slug text NOT NULL UNIQUE,
  lat double precision NOT NULL,
  lng double precision NOT NULL,
  altitud_m integer,
  descripcion text NOT NULL,
  como_llegar text NOT NULL,
  mejor_epoca text NOT NULL,
  foto text,
  datos_json jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS lugar_zona_id_idx ON lugar(zona_id);

